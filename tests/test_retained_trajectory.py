def test_save_trajectory_writes_atomically_and_round_trips(tmp_path: Path) -> None:
    Z = torch.arange(51 * 6, dtype=torch.float32).reshape(51, 6)
    path = tmp_path / RT.trajectory_filename(7)
    meta = RT.save_trajectory(
        path, Z=Z, latent_shape=[1, 2, 3], sigmas=[float(i) for i in range(51)],
        prompt_idx=7, seed=49, num_steps=50, store_dtype="bf16",
        extra={"backbone": "flux"},
    )
    assert path.name == "latents_00007.pt"
    assert not list(tmp_path.glob("*.tmp.*"))
    stored = torch.load(path, weights_only=True)
    assert stored["path"].dtype == torch.bfloat16
    assert stored["dims"] == [51, 6]
    assert stored["prompt_idx"] == 7 and stored["seed"] == 49
    assert stored["backbone"] == "flux"
    assert meta["z_T_sha256"] == stored["z_T_sha256"]
    assert torch.equal(stored["path"].to(torch.float32), Z.to(torch.bfloat16).to(torch.float32))


def test_save_trajectory_fp32_keeps_every_bit(tmp_path: Path) -> None:
    Z = torch.randn(51, 6, generator=torch.Generator().manual_seed(0))
    path = tmp_path / RT.trajectory_filename(0)
    RT.save_trajectory(path, Z=Z, latent_shape=[1, 6], sigmas=[0.0] * 51,
                       prompt_idx=0, seed=42, num_steps=50, store_dtype="fp32")
    stored = torch.load(path, weights_only=True)
    assert stored["path_dtype"] == "fp32"
    assert torch.equal(stored["path"], Z)
