"""Unit tests for the two SPX-runner retention flags.

`docs/image_cached_trajectory_plan_zh.md` section 7.1 adds `--retain_trajectory`
and `--prompt_indices` to `flux/sp_cross_runner.py` and
`qwen_image/sp_cross_runner.py`, and reuses the same runners for the reference
wave through an all-zero schedule file. The 257 stored SPX cells are replayed by
this same code, and the replay is only usable if it reproduces them, so what is
asserted here is:

  * both flags default to the behaviour the cells were generated with;
  * the step callback captures exactly `num_steps + 1` states and the run it
    watches is bit-identical to the same run without it;
  * `--prompt_indices` selects global indices and never renumbers them (the seed
    is `base_seed + global_idx`, so a renumbering would change the noise);
  * an all-zero schedule file is a legal schedule with no cache step, which is
    how the reference wave is generated by the cell runner rather than a second
    code path.
"""

