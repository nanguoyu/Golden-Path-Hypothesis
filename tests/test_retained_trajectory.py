# ---------------------------------------------------------------------------
# the callback captures exactly num_steps + 1 states, and changes nothing
# ---------------------------------------------------------------------------


class _FakePipe:
    """A sampler with the diffusers `callback_on_step_end` contract.

    It walks a deterministic seeded path so the same call twice gives the same
    states, which is what lets the test compare the watched run against the
    unwatched one bit for bit.
    """

    def __init__(self, num_steps: int = 50, shape=(1, 4, 8)) -> None:
        self.num_steps = num_steps
        self.shape = shape
        self.scheduler = SimpleNamespace(
            sigmas=torch.linspace(1.0, 0.0, num_steps + 1)
        )

    def prepare_latents(self, seed: int):
        g = torch.Generator().manual_seed(int(seed))
        return torch.randn(self.shape, generator=g, dtype=torch.float32)

    def __call__(self, seed: int, callback_on_step_end=None,
                 callback_on_step_end_tensor_inputs=None):
        latents = self.prepare_latents(seed)
        for step in range(self.num_steps):
            latents = latents * 0.98 + float(step) * 1e-3
            if callback_on_step_end is not None:
                out = callback_on_step_end(self, step, self.scheduler.sigmas[step],
                                           {"latents": latents})
                latents = out["latents"]
        return latents


def test_capture_sees_every_state_and_perturbs_nothing() -> None:
    pipe = _FakePipe()
    plain = pipe(seed=42)

    holder = RT.install_z_t_capture(pipe)
    trace, cb = RT.make_step_collector()
    watched = pipe(seed=42, callback_on_step_end=cb,
                   callback_on_step_end_tensor_inputs=["latents"])
    holder["_restore"]()

    assert torch.equal(plain, watched)
    assert len(trace) == pipe.num_steps
    Z = RT.stack_trajectory(holder.pop("z_T"), trace, num_steps=pipe.num_steps)
    assert Z.shape == (pipe.num_steps + 1, 32)
    # z_T is the pipeline's own initial latent, and the last row is the result
    assert torch.equal(Z[0], pipe.prepare_latents(42).reshape(-1))
    assert torch.equal(Z[-1], watched.reshape(-1).to(torch.float32))
    # restoring puts the pipeline's own method back
    assert not hasattr(pipe.prepare_latents, "__wrapped__")


def test_stack_trajectory_refuses_a_short_or_missing_capture() -> None:
    trace, _ = RT.make_step_collector()
    with pytest.raises(RuntimeError):
        RT.stack_trajectory(torch.zeros(4), trace, num_steps=3)
    trace.extend(torch.zeros(4) for _ in range(3))
    with pytest.raises(RuntimeError):
        RT.stack_trajectory(None, trace, num_steps=3)


def test_scheduler_sigmas_length_is_checked() -> None:
    pipe = _FakePipe(num_steps=50)
    assert len(RT.scheduler_sigmas(pipe, num_steps=50)) == 51
    with pytest.raises(RuntimeError):
        RT.scheduler_sigmas(pipe, num_steps=49)


