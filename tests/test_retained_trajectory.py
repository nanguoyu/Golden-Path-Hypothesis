def _parse(module, argv: list[str]):
    old = sys.argv
    sys.argv = ["runner", *argv]
    try:
        return module.parse_args()
    finally:
        sys.argv = old


def _minimal_argv(schedule: Path, prompts: Path, out: Path) -> list[str]:
    return [
        "--schedule_file", str(schedule),
        "--payload", "reuse",
        "--prompt_file", str(prompts),
        "--output_dir", str(out),
    ]


@pytest.fixture()
def files(tmp_path: Path):
    schedule = tmp_path / "sched.txt"
    schedule.write_text("0" * 50, encoding="utf-8")
    prompts = tmp_path / "prompts.txt"
    prompts.write_text("\n".join(f"prompt {i}" for i in range(12)), encoding="utf-8")
    return SimpleNamespace(schedule=schedule, prompts=prompts, out=tmp_path / "out")


def test_defaults_are_the_stored_cell_behaviour(files) -> None:
    for module in (FLUX, QWEN):
        args = _parse(module, _minimal_argv(files.schedule, files.prompts, files.out))
        assert args.retain_trajectory is False
        assert args.retain_dtype == "bf16"
        assert args.prompt_indices is None


def test_retention_flags_parse(files) -> None:
    for module in (FLUX, QWEN):
        args = _parse(module, _minimal_argv(files.schedule, files.prompts, files.out)
                      + ["--retain_trajectory", "--retain_dtype", "fp32",
                         "--prompt_indices", "3,7"])
        assert args.retain_trajectory is True
        assert args.retain_dtype == "fp32"
        assert args.prompt_indices == "3,7"


