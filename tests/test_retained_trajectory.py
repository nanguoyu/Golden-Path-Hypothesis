def test_select_pairs_keeps_global_indices() -> None:
    prompts = [f"p{i}" for i in range(6)]
    assert RT.select_pairs(prompts, indices=None) == list(enumerate(prompts))
    assert RT.select_pairs(prompts, indices=[4, 1]) == [(4, "p4"), (1, "p1")]


def test_selected_indices_shard_without_renumbering() -> None:
    """Sharding splits the SELECTION, and each element keeps its own index."""
    from lib.io_utils import seed_for, split_shard

    prompts = [f"p{i}" for i in range(12)]
    chosen = RT.parse_prompt_indices("1,4,5,9", total=len(prompts))
    pairs = RT.select_pairs(prompts, indices=chosen)
    seen: list[tuple[int, str]] = []
    for shard in range(3):
        lo, hi = split_shard(len(pairs), 3, shard)
        seen.extend(pairs[lo:hi])
    assert seen == [(1, "p1"), (4, "p4"), (5, "p5"), (9, "p9")]
    assert [seed_for(42, idx) for idx, _ in seen] == [43, 46, 47, 51]


